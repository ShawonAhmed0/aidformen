-- =============================================================================
-- Aid For Men Foundation — private chatbot history
-- =============================================================================
-- Visitor identity and full conversations are private operational data. Public
-- clients cannot read either table and cannot write to them directly. Two
-- narrowly-scoped SECURITY DEFINER functions create a session and append one
-- validated exchange; administrators alone can read the history through RLS.
-- =============================================================================

begin;

alter table public.chatbot_settings
  add column if not exists history_retention_days integer not null default 90;

alter table public.chatbot_settings
  drop constraint if exists chatbot_settings_history_retention_sane;

alter table public.chatbot_settings
  add constraint chatbot_settings_history_retention_sane
  check (history_retention_days between 7 and 365);

create table if not exists public.chat_conversations (
  id             uuid primary key default gen_random_uuid(),
  access_token   uuid not null default gen_random_uuid(),
  visitor_name   text not null,
  phone          text not null,
  locale         text not null default 'bn' check (locale in ('bn', 'en')),
  summary        text,
  message_count  integer not null default 0 check (message_count between 0 and 100),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create table if not exists public.chat_messages (
  id               bigint generated by default as identity primary key,
  conversation_id  uuid not null references public.chat_conversations (id) on delete cascade,
  role              text not null check (role in ('user', 'assistant')),
  content           text not null check (char_length(content) between 1 and 4000),
  created_at        timestamptz not null default now()
);

create unique index if not exists chat_conversations_access_token_idx
  on public.chat_conversations (id, access_token);

create index if not exists chat_conversations_recent_idx
  on public.chat_conversations (updated_at desc);

create index if not exists chat_messages_conversation_idx
  on public.chat_messages (conversation_id, id);

drop trigger if exists chat_conversations_set_updated_at on public.chat_conversations;
create trigger chat_conversations_set_updated_at
  before update on public.chat_conversations
  for each row execute function public.set_updated_at();

alter table public.chat_conversations enable row level security;
alter table public.chat_messages enable row level security;

-- Table writes always go through the two validated functions below. Admins
-- may inspect and remove retained conversations, while public visitors cannot
-- enumerate phone numbers, tokens, or transcripts through PostgREST.
revoke all on table public.chat_conversations from anon, authenticated;
revoke all on table public.chat_messages from anon, authenticated;
grant select, delete on table public.chat_conversations to authenticated;
grant select, delete on table public.chat_messages to authenticated;

drop policy if exists chat_conversations_admin_read on public.chat_conversations;
create policy chat_conversations_admin_read on public.chat_conversations
  for select using (public.is_admin());

drop policy if exists chat_conversations_admin_delete on public.chat_conversations;
create policy chat_conversations_admin_delete on public.chat_conversations
  for delete using (public.is_admin());

drop policy if exists chat_messages_admin_read on public.chat_messages;
create policy chat_messages_admin_read on public.chat_messages
  for select using (public.is_admin());

drop policy if exists chat_messages_admin_delete on public.chat_messages;
create policy chat_messages_admin_delete on public.chat_messages
  for delete using (public.is_admin());

create or replace function public.start_chat_conversation(
  p_visitor_name text,
  p_phone text,
  p_locale text default 'bn'
)
returns table (conversation_id uuid, conversation_token uuid)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_name text := regexp_replace(btrim(coalesce(p_visitor_name, '')), '[[:space:]]+', ' ', 'g');
  v_phone text := regexp_replace(
    translate(coalesce(p_phone, ''), '০১২৩৪৫৬৭৮৯', '0123456789'),
    '[[:space:]()-]',
    '',
    'g'
  );
  v_locale text := case when p_locale = 'en' then 'en' else 'bn' end;
  v_id uuid;
  v_token uuid;
  v_retention integer;
begin
  if char_length(v_name) < 2 or char_length(v_name) > 100 then
    raise exception 'Name must be between 2 and 100 characters';
  end if;

  if v_phone !~ '^01[3-9][0-9]{8}$' then
    raise exception 'A valid 11-digit Bangladesh mobile number is required';
  end if;

  -- A direct caller with the public anon key cannot create an unlimited number
  -- of sessions for the same number in a short burst.
  if (
    select count(*)
    from public.chat_conversations
    where phone = v_phone and created_at > now() - interval '1 hour'
  ) >= 5 then
    raise exception 'Too many chat sessions. Please try again later';
  end if;

  select history_retention_days
  into v_retention
  from public.chatbot_settings
  where id = true;

  delete from public.chat_conversations
  where updated_at < now() - make_interval(days => coalesce(v_retention, 90));

  insert into public.chat_conversations (visitor_name, phone, locale)
  values (v_name, v_phone, v_locale)
  returning id, access_token into v_id, v_token;

  return query select v_id, v_token;
end;
$$;

create or replace function public.append_chat_exchange(
  p_conversation_id uuid,
  p_conversation_token uuid,
  p_user_message text,
  p_assistant_message text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user text := btrim(coalesce(p_user_message, ''));
  v_assistant text := btrim(coalesce(p_assistant_message, ''));
  v_count integer;
  v_summary text;
begin
  if char_length(v_user) < 1 or char_length(v_user) > 1000 then
    return false;
  end if;

  if char_length(v_assistant) < 1 or char_length(v_assistant) > 4000 then
    return false;
  end if;

  select message_count
  into v_count
  from public.chat_conversations
  where id = p_conversation_id and access_token = p_conversation_token
  for update;

  if not found or v_count > 98 then
    return false;
  end if;

  insert into public.chat_messages (conversation_id, role, content)
  values
    (p_conversation_id, 'user', v_user),
    (p_conversation_id, 'assistant', v_assistant);

  -- A compact, deterministic summary of the visitor's four latest questions.
  -- This avoids a second paid AI request while keeping the admin list useful;
  -- the complete transcript remains in chat_messages immediately below it.
  select string_agg(recent.snippet, ' • ' order by recent.id)
  into v_summary
  from (
    select
      id,
      left(regexp_replace(content, '[[:space:]]+', ' ', 'g'), 120) as snippet
    from public.chat_messages
    where conversation_id = p_conversation_id and role = 'user'
    order by id desc
    limit 4
  ) recent;

  update public.chat_conversations
  set
    summary = v_summary,
    message_count = message_count + 2
  where id = p_conversation_id;

  return true;
end;
$$;

revoke all on function public.start_chat_conversation(text, text, text) from public;
revoke all on function public.append_chat_exchange(uuid, uuid, text, text) from public;

grant execute on function public.start_chat_conversation(text, text, text)
  to anon, authenticated;
grant execute on function public.append_chat_exchange(uuid, uuid, text, text)
  to anon, authenticated;

-- Identity sequences do not need to be exposed: append_chat_exchange runs as
-- the function owner and is the only public write path.
revoke all on sequence public.chat_messages_id_seq from anon, authenticated;

commit;

